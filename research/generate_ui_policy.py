#!/usr/bin/env python3
"""Generate the browser copy of the UI decision policy.

Source of truth: config/ui-decision-policy.json (see docs/current/UI_CONTRACT.md).
Output:          app/generated/ui-decision-policy.js  (window.FIE_UI_POLICY, frozen)

The output is deterministic (sorted keys, no timestamp) so an unchanged policy
produces byte-identical deploy files and build-manifest hashes.
"""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'config' / 'ui-decision-policy.json'
OUT = ROOT / 'app' / 'generated' / 'ui-decision-policy.js'


def validate(policy: dict) -> None:
    assert policy.get('schema_version') == 1, 'unsupported ui policy schema'
    assert policy.get('default_ui') in {'classic', 'v10'}, 'default_ui must be classic or v10'
    t = policy['thresholds']
    assert 0 < t['close_call'] < t['recommend'] < t['urgent'], 'thresholds must satisfy close_call < recommend < urgent'
    s = policy['status']
    assert set(s['zero']).isdisjoint(s['monitor']), 'a status cannot be both zero-valued and monitor-only'
    assert 'Doubtful' in s['zero'], 'Doubtful is treated as out (user decision 2026-10-18)'
    assert 0 <= s['doubtful_tiebreak_factor'] < 0.1, 'doubtful tie-break must stay a tie-break'
    assert s['waiver_add_policy']['never_claim_unavailable'] is True
    assert set(s.get('last_game_carry_over', [])) <= {'Out', 'Doubtful'}, 'only game designations can carry over from the last game (never IR/PUP/SUS/NA)'
    assert s.get('last_game_carry_over_min_hours', 108) >= 96, 'carry-over only before the week\'s first injury report (Wednesday for Sunday games): at least 96 h before kickoff'
    v = policy.get('variance', {})
    if v:
        assert v['mode'] in {'rule_of_thumb', 'calibrated'}, 'variance.mode is rule_of_thumb or calibrated'
        for pos, q in v.get('calibration', {}).get('positions', {}).items():
            assert 0 <= q['p10'] < q['p50'] < q['p90'], f'{pos}: p10 < p50 < p90'
            assert q['n'] >= 30, f'{pos}: calibration needs at least 30 observations'
    bd = policy.get('waivers', {}).get('bids', {})
    if bd:
        assert bd['own'] >= bd['same_type'] >= bd['other_type'] >= 0, 'bids: own league weighs most (user decision 2026-10-20)'
        assert 0 < bd['low_q'] < bd['high_q'] < 1, 'bids: 0 < low_q < high_q < 1'
        assert bd['rank_cap'] >= 1 and bd['recent_factor'] >= 1, 'bids: rank_cap >= 1, recent_factor >= 1'
    op = policy.get('opponents', {}).get('optimal_until', {})
    if op:
        assert op['weekday'] in range(7) and op['hour_utc'] in range(24), 'opponents.optimal_until: weekday 0-6 (0 = Sunday), hour_utc 0-23'
    rf = policy.get('refresh_seconds', {})
    if rf:
        assert 60 <= rf['live'] <= rf['idle'] <= rf['offseason'], 'refresh_seconds: 60 <= live <= idle <= offseason'
    for pos, ts in v.get('calibration', {}).get('tiers', {}).items():
        for t in ts:
            assert len(t['q']) == 9 and all(a <= b for a, b in zip(t['q'], t['q'][1:])), f'{pos}: tier deciles P10..P90 must be 9 non-decreasing ratios'
            assert t['n'] >= 30, f'{pos}: a tier needs at least 30 observations'
    assert v.get('calibration', {}).get('player_level', False) is False or v['calibration'].get('players'), 'player_level needs a players block'
    tm = policy.get('team', {})
    if tm:
        assert 0 < tm['thin_recovery'] < 1, 'team.thin_recovery is a share of the starter\'s points (0-1)'
    w = policy.get('waivers', {})
    if w:
        assert 1 <= w['horizon_weeks'] <= 6, 'waiver horizon 1-6 weeks'
        assert 0 < w['alert_week_gain'] <= w['alert_horizon_gain'], 'waiver alert gains must be positive and week <= horizon'
        assert set(w['long_term_zero']) <= set(s['zero']), 'long-term zero statuses must be zero-valued statuses'
        assert w['dynasty_protect_adp'] >= 0 and w['candidates_per_position'] >= 1 and w['overview_candidates'] >= 1


def render(policy: dict) -> str:
    body = json.dumps(policy, sort_keys=True, ensure_ascii=False, separators=(',', ':'))
    return ('/* GENERATED by research/generate_ui_policy.py from config/ui-decision-policy.json. Do not edit. */\n'
            "(function(){'use strict';\n"
            'const deepFreeze=o=>{if(o&&typeof o===\'object\'){Object.values(o).forEach(deepFreeze);Object.freeze(o);}return o;};\n'
            f'window.FIE_UI_POLICY=deepFreeze({body});\n'
            '})();\n')


def main() -> None:
    policy = json.loads(SRC.read_text(encoding='utf-8'))
    validate(policy)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = render(policy)
    if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
        OUT.write_text(text, encoding='utf-8', newline='\n')
        print(f'wrote {OUT.relative_to(ROOT)}')
    else:
        print(f'unchanged {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
