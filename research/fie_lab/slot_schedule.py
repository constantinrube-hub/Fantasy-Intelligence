#!/usr/bin/env python3
"""
slot_schedule.py: Windows Task Scheduler entries for every kickoff slot of one NFL week.

Author: Claude (for Constantin), 30 Oct 2026 (readiness item c4). Python 3.9+ standard library only.
Reads the free Odds API events list (0 credits), groups the week's games into kickoff slots exactly as
slot_capture.py does, and WRITES a PowerShell script. It registers nothing itself: you read the script,
then run it. Nothing is written to the FIE repository.

RUN (PowerShell, e.g. Tuesday night after the component run)
  py -3 slot_schedule.py --week 9 --lab C:\\Users\\User\\FIE\\FIE-Lab
  # review register_slots_w09.ps1, then:
  powershell -ExecutionPolicy Bypass -File C:\\Users\\User\\FIE\\FIE-Lab\\slots\\register_slots_w09.ps1
  # remove the week's tasks (e.g. after a schedule change), then re-generate:
  powershell -ExecutionPolicy Bypass -File C:\\Users\\User\\FIE\\FIE-Lab\\slots\\unregister_slots_w09.ps1

WHAT EACH TASK DOES
  Starts at (first kickoff - --lead minutes, default 80) and runs
    py -3 <lab>\\slot_capture.py --week W --slot-kickoff <UTC> --out <lab>\\slots
  Times are written in UTC and converted to your PC's local time by PowerShell, so the US/EU clock
  changes cannot shift them. Settings: wake the PC from sleep (needs "Allow wake timers" in the power
  plan), start as soon as possible if the time was missed (the capture then flags itself LATE), stop
  after 30 minutes, run only while you are logged on (no password stored). ODDS_API_KEY must be a USER
  environment variable (setx), which the task inherits.

CHANGE LOG
  v1 (30 Oct 2026): first version.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import slot_capture as sc  # noqa: E402

TASK_PREFIX = "FIE Slot"


def week_slots(events: list, now: datetime, week_start_after: datetime | None = None) -> list[dict]:
    """Slots of the NFL week of the earliest upcoming game (or of the first game after week_start_after)."""
    upcoming = [e for e in events if sc.utc(e["commence_time"]) > (week_start_after or now)]
    if not upcoming:
        return []
    first = min(sc.utc(e["commence_time"]) for e in upcoming)
    end = sc.week_end(first)
    week = [e for e in upcoming if sc.utc(e["commence_time"]) < end]
    return sc.slots_from_events(week)


def ps_quote(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def render(slots: list[dict], week: int, season: int, lab: str, python: str, lead: int, out: str) -> tuple[str, str, list]:
    rows, reg, unreg = [], [], []
    script = str(Path(lab) / "slot_capture.py") if "\\" not in lab else lab.rstrip("\\") + "\\slot_capture.py"
    for s in slots:
        start = s["first_kickoff"] - timedelta(minutes=lead)
        name = f"{TASK_PREFIX} W{week:02d} {s['label']}"
        args = (f'"{script}" --week {week} --season {season} --slot-kickoff {sc.iso(s["first_kickoff"])} '
                f'--out "{out}"')
        games = "; ".join(f"{e.get('away_team')} @ {e.get('home_team')}" for e in s["events"])
        rows.append({"task": name, "start_utc": sc.iso(start), "first_kickoff_utc": sc.iso(s["first_kickoff"]),
                     "cutoff_target_utc": sc.iso(s["cutoff"]), "games": len(s["events"]), "matchups": games})
        exe, pre = (python.split(" ", 1) + [""])[:2]
        reg.append(f"""
# {name}: {games}
$at = [DateTime]::Parse('{sc.iso(start)}', [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::AdjustToUniversal).ToLocalTime()
if ($at -lt (Get-Date)) {{ Write-Host 'skip (already past): {name}' -ForegroundColor Yellow }} else {{
  $action = New-ScheduledTaskAction -Execute {ps_quote(exe)} -Argument {ps_quote((pre + ' ' + args).strip())} -WorkingDirectory {ps_quote(lab)}
  $trigger = New-ScheduledTaskTrigger -Once -At $at
  Register-ScheduledTask -TaskName {ps_quote(name)} -Action $action -Trigger $trigger -Settings $settings -Description {ps_quote('FIE slot capture, first kickoff ' + sc.iso(s['first_kickoff']) + ' UTC. Generated by slot_schedule.py v1.')} -Force | Out-Null
  Write-Host ('registered: {name} at ' + $at.ToString('ddd dd MMM HH:mm'))
}}""")
        unreg.append(f"Unregister-ScheduledTask -TaskName {ps_quote(name)} -Confirm:$false -ErrorAction SilentlyContinue")
    head = f"""# register_slots_w{week:02d}.ps1 - generated {sc.iso(datetime.now(timezone.utc))} by slot_schedule.py v1 (readiness c4).
# {len(slots)} slot task(s) for NFL week {week}. Review, then run. Re-running replaces the same task names (-Force).
$ErrorActionPreference = 'Stop'
if (-not [Environment]::GetEnvironmentVariable('ODDS_API_KEY', 'User')) {{ Write-Host 'WARNING: ODDS_API_KEY is not a user variable; tasks will capture Sleeper only.' -ForegroundColor Yellow }}
$settings = New-ScheduledTaskSettingsSet -WakeToRun -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Minutes 30) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
"""
    return head + "".join(reg) + "\n", "\n".join(unreg) + "\n", rows


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate Task Scheduler entries for one week's kickoff slots.")
    ap.add_argument("--week", type=int, required=True)
    ap.add_argument("--season", type=int, default=2026)
    ap.add_argument("--lab", required=True, help="FIE Lab folder on your PC (holds slot_capture.py)")
    ap.add_argument("--out", help="capture folder (default <lab>\\slots)")
    ap.add_argument("--python", default="py -3", help="interpreter command used by the tasks")
    ap.add_argument("--lead", type=int, default=80, help="minutes before the first kickoff (default 80, cutoff T-75)")
    ap.add_argument("--events", help="use a saved events.json instead of calling the API (testing)")
    a = ap.parse_args(argv)
    out = a.out or (a.lab.rstrip("\\/") + ("\\slots" if "\\" in a.lab else "/slots"))
    if a.events:
        events = json.loads(Path(a.events).read_text(encoding="utf-8"))
    else:
        key = os.environ.get("ODDS_API_KEY")
        if not key:
            print("ODDS_API_KEY is not set (the events list is free but needs the key)", file=sys.stderr)
            return 2
        st, events, _, _ = sc.odds_get("/events", {"apiKey": key})
        if st != 200 or not isinstance(events, list):
            print(f"/events failed: HTTP {st}", file=sys.stderr)
            return 1
    slots = week_slots(events, datetime.now(timezone.utc))
    if not slots:
        print("no upcoming games in the events list", file=sys.stderr)
        return 1
    reg, unreg, rows = render(slots, a.week, a.season, a.lab, a.python, a.lead, out)
    folder = Path(out)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"register_slots_w{a.week:02d}.ps1").write_text(reg, encoding="utf-8-sig")
    (folder / f"unregister_slots_w{a.week:02d}.ps1").write_text(unreg, encoding="utf-8-sig")
    (folder / f"slots_w{a.week:02d}.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    print(f"{len(rows)} slot(s), week {a.week}:")
    for r in rows:
        print(f"  start {r['start_utc']}  kickoff {r['first_kickoff_utc']}  {r['games']:>2} game(s)  {r['task']}")
    print(f"wrote {folder / f'register_slots_w{a.week:02d}.ps1'} (review, then run it)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
